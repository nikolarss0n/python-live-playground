it('right-clicks a folder, creates a child file, renames its subtree, and confirms recursive deletion', async () => {
  const user = userEvent.setup()
  const mounted = render(<Harness />)
  const context = (path: string) => user.pointer({ keys: '[MouseRight]', target: screen.getByTitle(path) })
  await context('data')
  await user.click(screen.getByRole('menuitem', { name: 'New File…' }))
  await user.type(screen.getByLabelText('File name'), 'nested/notes.txt{Enter}')
  expect(screen.getByRole('tab', { name: 'data/nested/notes.txt', selected: true })).toBeInTheDocument()
  await context('data')
  await user.click(screen.getByRole('menuitem', { name: 'Rename…' }))
  const name = screen.getByLabelText('New folder name')
  await user.clear(name)
  await user.type(name, 'mail_tools{Enter}')
  expect(screen.getByRole('alert')).toHaveTextContent(/exists/)
  await user.clear(name)
  await user.type(name, 'records{Enter}')
  expect(screen.getByRole('tab', { name: 'records/nested/notes.txt', selected: true })).toBeInTheDocument()
  await context('records')
  await user.click(screen.getByRole('menuitem', { name: 'Delete…' }))
  await user.click(screen.getByRole('button', { name: 'Cancel' }))
  expect(screen.getByTitle('records')).toHaveFocus()
  await user.keyboard('{Shift>}{F10}{/Shift}')
  await user.click(screen.getByRole('menuitem', { name: 'Delete…' }))
  await user.click(screen.getByRole('button', { name: 'Delete folder' }))
  mounted.unmount()
  render(<Harness />)
  expect(screen.queryByTitle('records')).toBeNull()
  expect(screen.queryByRole('tab', { name: 'records/nested/notes.txt' })).toBeNull()
  expect(screen.getByRole('tab', { name: 'main.py', selected: true })).toBeInTheDocument()
})

it('shows file actions for the clicked file and creation actions on the Explorer background', async () => {
  const user = userEvent.setup()
  render(<Harness />)
  const files = screen.getByRole('navigation', { name: 'Project files' })
  await user.pointer({ keys: '[MouseRight]', target: within(files).getByText('main.py') })
  expect(screen.getByRole('menu', { name: 'File actions for main.py' })).toBeInTheDocument()
  expect(screen.getByRole('menuitem', { name: 'Delete…' })).toBeDisabled()
  await user.keyboard('{Escape}')
  await user.pointer({ keys: '[MouseRight]', target: within(files).getByText('mails.csv') })
  await user.click(screen.getByRole('menuitem', { name: 'Rename…' }))
  const input = screen.getByLabelText('New file name')
  await user.clear(input)
  await user.type(input, 'contacts.csv{Enter}')
  expect(within(files).getByTitle('data/contacts.csv')).toBeInTheDocument()
  await user.pointer({ keys: '[MouseRight]', target: files })
  const root = within(screen.getByRole('menu', { name: 'Project actions' }))
  expect(root.queryByRole('menuitem', { name: 'Delete…' })).toBeNull()
  await user.click(root.getByRole('menuitem', { name: 'New File…' }))
  await user.type(screen.getByLabelText('File name'), 'notes.txt{Enter}')
  expect(within(files).getByTitle('notes.txt')).toBeInTheDocument()
})
