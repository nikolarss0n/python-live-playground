import { render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, expect, it } from 'vitest'
import { ProjectExplorer, ProjectFileBar } from './ProjectNavigation'
import { useProjectWorkspace } from './useProjectWorkspace'

function Harness() {
  const workspace = useProjectWorkspace()
  const props = { workspace, counts: { 'mail_tools/mask.py': { results: 4, errors: 1 } } }
  return <><ProjectExplorer {...props}/><ProjectFileBar {...props}/></>
}

beforeEach(() => localStorage.clear())

it('shows the last run beside its source and keeps tree selection and keyboard tabs in sync', async () => {
  const user = userEvent.setup()
  render(<Harness />)
  const tree = screen.getByRole('navigation', { name: 'Project files' })
  const folder = within(tree).getByRole('button', { name: 'mail_tools' })
  await user.click(folder)
  expect(within(tree).queryByTitle('mail_tools/mask.py')).toBeNull()
  await user.click(folder)
  const mask = within(tree).getByTitle('mail_tools/mask.py')
  expect(within(mask).getByRole('img', { name: '4 results' })).toBeInTheDocument()
  expect(within(mask).getByRole('img', { name: '1 error' })).toBeInTheDocument()
  await user.click(mask)
  const tab = screen.getByRole('tab', { name: 'mail_tools/mask.py', selected: true })
  expect(mask).toHaveAttribute('aria-current')
  tab.focus()
  await user.keyboard('{ArrowRight}')
  expect(screen.getByRole('tab', { name: 'data/mails.csv', selected: true })).toHaveFocus()
  await user.keyboard('{Delete}')
  expect(tab).toHaveFocus()
  expect(screen.queryByRole('tab', { name: 'data/mails.csv' })).toBeNull()
})

it('creates a nested file after correcting a duplicate path', async () => {
  const user = userEvent.setup()
  render(<Harness />)
  await user.click(screen.getByRole('button', { name: 'New file' }))
  const field = screen.getByLabelText('File path')
  await user.type(field, 'main.py{Enter}')
  expect(screen.getByRole('alert')).toHaveTextContent(/exists/)
  await user.clear(field)
  await user.type(field, 'tools/format.py{Enter}')
  expect(screen.getByRole('tab', { name: 'tools/format.py', selected: true })).toBeInTheDocument()
  expect(screen.getByRole('button', { name: 'tools' })).toHaveAttribute('aria-expanded', 'true')
})

it('returns focus to the drawer toggle when a file is picked or Escape is pressed', async () => {
  const user = userEvent.setup()
  const { container } = render(<Harness />)
  const toggle = screen.getByLabelText('Open project files')
  await user.click(toggle)
  const drawer = screen.getByRole('dialog', { name: 'Project explorer' })
  expect(container).toHaveAttribute('inert')
  await user.click(within(drawer).getByTitle('mail_tools/mask.py'))
  expect(toggle).toHaveFocus()
  expect(screen.getByRole('tab', { name: 'mail_tools/mask.py', selected: true })).toBeInTheDocument()
  await user.click(toggle)
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).toBeNull()
  expect(toggle).toHaveFocus()
})

it('moves an open file and protects the selected entry point from deletion', async () => {
  const user = userEvent.setup()
  render(<Harness />)
  await user.click(screen.getByRole('tab', { name: 'main.py' }))
  await user.click(screen.getByRole('button', { name: 'Actions for main.py' }))
  expect(screen.getByRole('button', { name: 'Delete file…' })).toBeDisabled()
  const tab = screen.getByRole('tab', { name: 'mail_tools/mask.py' })
  await user.click(tab)
  await user.click(screen.getByRole('button', { name: 'Actions for mail_tools/mask.py' }))
  await user.click(screen.getByRole('button', { name: 'Rename or move…' }))
  const field = screen.getByLabelText('New file path')
  await user.clear(field)
  await user.type(field, 'jobs/mask.py{Enter}')
  expect(screen.getByRole('tab', { name: 'jobs/mask.py', selected: true })).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Actions for jobs/mask.py' }))
  await user.click(screen.getByRole('button', { name: 'Set as entry file' }))
  expect(within(screen.getByRole('navigation')).getByTitle('jobs/mask.py')).toHaveTextContent('main')
  await user.click(screen.getByRole('button', { name: 'Actions for jobs/mask.py' }))
  expect(screen.getByRole('button', { name: 'Delete file…' })).toBeDisabled()
})

it('requires a separate confirmation to delete from the drawer', async () => {
  const user = userEvent.setup()
  render(<Harness />)
  await user.click(screen.getByRole('tab', { name: 'data/mails.csv' }))
  await user.click(screen.getByLabelText('Open project files'))
  const drawer = within(screen.getByRole('dialog'))
  const actions = drawer.getByRole('button', { name: 'Actions for data/mails.csv' })
  await user.click(actions)
  expect(drawer.getByRole('button', { name: 'Set as entry file' })).toBeDisabled()
  await user.click(drawer.getByRole('button', { name: 'Delete file…' }))
  expect(drawer.getByRole('button', { name: 'Cancel' })).toHaveFocus()
  await user.click(drawer.getByRole('button', { name: 'Cancel' }))
  expect(drawer.getByTitle('data/mails.csv')).toBeInTheDocument()
  await user.click(actions)
  await user.click(drawer.getByRole('button', { name: 'Delete file…' }))
  await user.click(drawer.getByRole('button', { name: 'Delete file', exact: true }))
  expect(drawer.queryByTitle('data/mails.csv')).toBeNull()
})

it('creates empty folders inline, restores them, and creates files in the selected folder', async () => {
  const user = userEvent.setup()
  const mounted = render(<Harness />)
  const add = screen.getByRole('button', { name: 'New folder' })
  await user.click(add)
  const name = screen.getByRole('textbox', { name: 'Folder name' })
  expect(name).toHaveFocus()
  await user.type(name, 'data{Enter}')
  expect(screen.getByRole('alert')).toHaveTextContent(/exists/)
  await user.clear(name)
  await user.type(name, 'reports{Enter}')
  expect(screen.getByTitle('reports')).toHaveFocus()
  await user.click(add)
  await user.type(screen.getByRole('textbox', { name: 'Folder name' }), 'weekly{Enter}')
  mounted.unmount()
  render(<Harness />)
  await user.click(screen.getByTitle('reports/weekly'))
  await user.click(screen.getByRole('button', { name: 'New file' }))
  expect(screen.getByLabelText('File path')).toHaveValue('reports/weekly/')
})

